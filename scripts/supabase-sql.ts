import { readdir, readFile, mkdir, writeFile } from "node:fs/promises";
const migrations = await Promise.all(
  (await readdir("migrations"))
    .filter((n) => n.endsWith(".sql"))
    .sort()
    .map(async (name) => ({
      name,
      sql: await readFile("migrations/" + name, "utf8"),
    })),
);
const tables = [
  ...new Set(
    migrations.flatMap((m) =>
      [...m.sql.matchAll(/CREATE TABLE(?: IF NOT EXISTS)?\s+([a-z_]+)/g)].map(
        (match) => match[1],
      ),
    ),
  ),
];
let sql = `-- Generated by npm run supabase:sql. Run in the Supabase SQL Editor as postgres.
-- Contains schema only, no secrets or demo users. Each migration is applied once.
BEGIN;
SELECT pg_advisory_xact_lock(981734);
DO $preflight$
BEGIN
  IF EXISTS(SELECT 1 FROM pg_tables WHERE schemaname='public' AND tablename=ANY(ARRAY[${tables.map((t) => "'" + t + "'").join(",")}])) THEN
    IF to_regclass('public.users') IS NULL OR to_regclass('public.schema_migrations') IS NULL THEN
      RAISE EXCEPTION 'Colliding public tables: use a separate Supabase project';
    END IF;
    IF (SELECT count(*) FROM information_schema.columns WHERE table_schema='public' AND table_name='users' AND column_name IN ('public_id','phone_verified','identity','dob')) <> 4 THEN
      RAISE EXCEPTION 'Existing users table is not Yolda: nothing was migrated';
    END IF;
    IF NOT EXISTS(SELECT 1 FROM public.schema_migrations WHERE name='001.sql') THEN
      RAISE EXCEPTION 'Existing migration history is not initialized Yolda: nothing was migrated';
    END IF;
  END IF;
END $preflight$;
CREATE TABLE IF NOT EXISTS schema_migrations(name text PRIMARY KEY,applied_at timestamptz DEFAULT now());
DO $bootstrap$
BEGIN
`;
for (const { name, sql: migrationSQL } of migrations) {
  const tag = "$migration" + name.replaceAll(".", "_") + "$";
  sql += `  IF NOT EXISTS(SELECT 1 FROM schema_migrations WHERE name='${name}') THEN\n    EXECUTE ${tag}\n${migrationSQL}\n${tag};\n    INSERT INTO schema_migrations(name) VALUES('${name}');\n  END IF;\n`;
}
sql += "END $bootstrap$;\nCOMMIT;\n";
await mkdir("supabase", { recursive: true });
await writeFile("supabase/bootstrap.sql", sql);
console.log("Wrote supabase/bootstrap.sql (no credentials)");
